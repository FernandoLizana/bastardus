"""Emit WidthClosure wrappers for residual axiom lists already in Lean.

Wraps existing `sampN` / `rcN` defs (axioms + topology) as `WidthClosure 3`
following `AltResidualClosures.lean`. Does not re-emit axiom lists.

Usage:
  python -m backend.proof_complexity.emit_residual_width_closures_lean --kind samples
  python -m backend.proof_complexity.emit_residual_width_closures_lean --kind catalog
"""

from __future__ import annotations

import argparse
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUT_DIR = ROOT / "lean" / "PNPLab"

# |ℓ| ≤ 12 in samples/catalog residuals
PIVOT_HI = 12


def pivots_list() -> str:
    vals = list(range(-PIVOT_HI, PIVOT_HI + 1))
    return "[" + ", ".join(str(v) for v in vals) + "]"


def emit_helper() -> str:
    return f"""/-
  Shared pivots + lit membership for residual WidthClosure synthesis.
  Generated by `emit_residual_width_closures_lean.py`.
-/

import PNPLab.K4Width3

namespace PNPLab.Resolution

/-- Pivot range covering residual literals (|ℓ| ≤ {PIVOT_HI}). -/
def residualSynthPivots : List Lit :=
  {pivots_list()}

theorem residual_lits_in_pivots (S : List Clause)
    (h : (S.all fun C => C.all fun lit => decide (lit ∈ residualSynthPivots)) = true)
    {{C D R : Clause}} {{p : Lit}}
    (hC : C ∈ S) (hRes : resolveOriented C D p = some R) :
    p ∈ residualSynthPivots := by
  obtain ⟨_, hpC, _⟩ := resolveOriented_some_mem hRes
  have hCall := (List.all_eq_true.mp h) C hC
  exact of_decide_eq_true ((List.all_eq_true.mp hCall) p hpC)

end PNPLab.Resolution
"""


def wrap_one(prefix: str, n: int) -> str:
    name = f"{prefix}{n}"
    return f"""
theorem {name}_lits_ok :
    ({name}RClosed.all fun C => C.all fun lit => decide (lit ∈ residualSynthPivots)) = true := by
  native_decide

theorem {name}_closed_bool : k4ClosedUnder {name}RClosed 3 residualSynthPivots = true := by
  native_decide

def {name}RClosure : WidthClosure 3 where
  axioms := {name}RAxioms
  mem := fun C => C ∈ {name}RClosed
  axiom_mem := by
    intro C hC _
    simpa [{name}RClosed] using hC
  closed := by
    intro C D R p hC hD hRes hw
    exact k4_mem_of_closed {name}_closed_bool hC hD hRes hw
      (residual_lits_in_pivots {name}RClosed {name}_lits_ok hC hRes)

theorem {name}_closure_no_empty : ¬ {name}RClosure.mem [] := by
  simp [{name}RClosure, {name}RClosed]
  exact {name}R_no_empty
"""


def emit_chunk(
    *,
    kind: str,
    part: int,
    prefix: str,
    import_mod: str,
    lo: int,
    hi: int,
    total_note: str,
) -> str:
    body = "".join(wrap_one(prefix, n) for n in range(lo, hi + 1))
    names = [f"{prefix}{n}RClosure" for n in range(lo, hi + 1)]
    no_empty = " ∧\n      ".join(f"¬ {c}.mem []" for c in names)
    proofs = ", ".join(f"{prefix}{n}_closure_no_empty" for n in range(lo, hi + 1))
    return f"""/-
  Residual WidthClosure synthesis ({kind} part {part}): `{prefix}{lo}`..`{prefix}{hi}`.
  {total_note}
  Generated by `emit_residual_width_closures_lean.py`.
-/

import PNPLab.{import_mod}
import PNPLab.ResidualSynthHelper

namespace PNPLab.Resolution
{body}
theorem all_{kind}_part{part}_RClosures_no_empty :
    {no_empty} :=
  ⟨{proofs}⟩

end PNPLab.Resolution
"""


def emit_samples_agg(n_parts: int) -> str:
    imports = "\n".join(
        f"import PNPLab.SampleResidualClosuresPart{i}" for i in range(1, n_parts + 1)
    )
    return f"""/-
  Aggregated sample residual WidthClosures (96/96).
  Generated by `emit_residual_width_closures_lean.py`.
-/

{imports}

namespace PNPLab.Resolution

/-- Packaging complete: 96 sample `WidthClosure`s across {n_parts} parts. -/
def sampleResidualClosuresCount : Nat := 96

theorem sampleResidualClosuresCount_eq :
    sampleResidualClosuresCount = 96 := rfl

def sampleResidualClosuresDoc : String :=
  "96 stratified residual samples packaged as WidthClosure 3"

end PNPLab.Resolution
"""


def emit_catalog_agg() -> str:
    return """/-
  Aggregated catalog residual WidthClosures (461/461).
  Generated by `emit_residual_width_closures_lean.py`.
-/

import PNPLab.CatalogResidualClosuresPart1
import PNPLab.CatalogResidualClosuresPart2
import PNPLab.CatalogResidualClosuresPart3
import PNPLab.ResidualClosureAll

namespace PNPLab.Resolution

def catalogResidualClosuresCount : Nat := 461

theorem catalogResidualClosuresCount_eq :
    catalogResidualClosuresCount = 461 := rfl

theorem catalog_residual_closures_mass_match :
    catalogResidualClosuresCount = crossingResidualCatalogMass.isoOk := by
  native_decide

def catalogResidualClosuresDoc : String :=
  "461 catalog residuals packaged as WidthClosure 3"

end PNPLab.Resolution
"""


def write_samples() -> list[Path]:
    # 96 samples in 6 chunks of 16
    chunk = 16
    written: list[Path] = []
    helper = OUT_DIR / "ResidualSynthHelper.lean"
    helper.write_text(emit_helper(), encoding="utf-8")
    written.append(helper)
    for part in range(1, 7):
        lo = (part - 1) * chunk + 1
        hi = part * chunk
        path = OUT_DIR / f"SampleResidualClosuresPart{part}.lean"
        path.write_text(
            emit_chunk(
                kind="samples",
                part=part,
                prefix="samp",
                import_mod="ResidualSampleCatalog",
                lo=lo,
                hi=hi,
                total_note="Stratified samples from ResidualSampleCatalog.",
            ),
            encoding="utf-8",
        )
        written.append(path)
    agg = OUT_DIR / "SampleResidualClosures.lean"
    agg.write_text(emit_samples_agg(6), encoding="utf-8")
    written.append(agg)
    return written


def write_catalog() -> list[Path]:
    # Match ResidualClosurePart splits: 154 + 154 + 153
    parts = [(1, 1, 154), (2, 155, 308), (3, 309, 461)]
    written: list[Path] = []
    helper = OUT_DIR / "ResidualSynthHelper.lean"
    if not helper.exists():
        helper.write_text(emit_helper(), encoding="utf-8")
        written.append(helper)
    for part, lo, hi in parts:
        path = OUT_DIR / f"CatalogResidualClosuresPart{part}.lean"
        path.write_text(
            emit_chunk(
                kind="catalog",
                part=part,
                prefix="rc",
                import_mod=f"ResidualClosurePart{part}",
                lo=lo,
                hi=hi,
                total_note="Full E2 catalog residuals from ResidualClosurePart*.",
            ),
            encoding="utf-8",
        )
        written.append(path)
    agg = OUT_DIR / "CatalogResidualClosures.lean"
    agg.write_text(emit_catalog_agg(), encoding="utf-8")
    written.append(agg)
    return written


def main() -> int:
    p = argparse.ArgumentParser()
    p.add_argument("--kind", choices=["samples", "catalog", "all"], default="all")
    args = p.parse_args()
    written: list[Path] = []
    if args.kind in ("samples", "all"):
        written.extend(write_samples())
    if args.kind in ("catalog", "all"):
        written.extend(write_catalog())
    for w in written:
        print(f"wrote {w.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
