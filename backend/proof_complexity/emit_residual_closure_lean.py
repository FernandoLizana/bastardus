"""Emit full residual closure Lean witnesses for all 461 E2 catalog instances (G5).

Recomputes RAxioms via `residual_of`, reuses catalog iso permutation (no flips),
streams three part files (~154 instances each) plus `ResidualClosureAll.lean`.
"""

from __future__ import annotations

import json
import textwrap
from pathlib import Path
from typing import TextIO

from backend.proof_complexity.emit_crossing_residual_catalog import (
    _clause_set,
    _extract_k4_axioms,
    _find_signed_iso,
    residual_of,
)

ROOT = Path(__file__).resolve().parents[2]
CATALOG = ROOT / "reports" / "discovery" / "crossing_residual_catalog.json"
LEAN_DIR = ROOT / "lean" / "PNPLab"
CHUNK = 154
EMIT_SCRIPT = "backend/proof_complexity/emit_residual_closure_lean.py"


def lean_clause(c: list[int] | tuple[int, ...]) -> str:
    if not c:
        return "[]"
    return "[" + ", ".join(f"({lit} : Lit)" for lit in c) + "]"


def list_clauses(name: str, clauses: list) -> str:
    lines = [f"def {name} : List Clause :="]
    for i, c in enumerate(clauses):
        pref = "  [ " if i == 0 else "  , "
        lines.append(pref + lean_clause(c))
    lines.append("  ]")
    return "\n".join(lines)


def _emit_instance_block(
    global_idx: int,
    inst: dict,
    res: dict,
    perm: list[int],
) -> str:
    n = inst["n"]
    c1, c2 = inst["chords"]
    tips = inst["tips"]
    pre = f"rc{global_idx}"
    vres = "[" + ", ".join(str(v) for v in res["Vres"]) + "]"
    perm_s = "[" + ", ".join(str(v) for v in perm) + "]"
    return textwrap.dedent(
        f"""
        /- Hop-{tips}: C_{n} + {c1},{c2}. -/
        def {pre}Vres : List Nat := {vres}
        {list_clauses(pre + "RAxioms", res["RAxioms"])}
        abbrev {pre}RClosed : List Clause := {pre}RAxioms

        theorem {pre}R_size : {pre}RClosed.length = 16 := by native_decide
        theorem {pre}Vres_len : {pre}Vres.length = 6 := by native_decide
        theorem {pre}R_no_empty : ¬ ([] ∈ {pre}RClosed) := by native_decide

        def {pre}TopologyRename : VarRename where
          src := {pre}Vres
          dst := {perm_s}
          src_len := {pre}Vres_len
          dst_len := by native_decide

        def {pre}TopologySetEq : Bool :=
          renamedSubset {pre}TopologyRename {pre}RClosed k4Closed &&
            renamedSurjective {pre}TopologyRename {pre}RClosed k4Closed

        theorem {pre}TopologySetEq_true : {pre}TopologySetEq = true := by native_decide
        """
    ).strip("\n") + "\n\n"


def _write_part_header(f: TextIO, part_idx: int, count: int, start_idx: int) -> None:
    f.write(
        textwrap.dedent(
            f"""\
            /-
              Full residual closure witnesses part {part_idx} (Category C / G5).
              {count} instances (rc{start_idx}..rc{start_idx + count - 1}): Vres, RAxioms,
              topology rename, and native_decide set-eq to `k4Closed`.

              Generated by `{EMIT_SCRIPT}`.
              E2 parent: `crossing_residual_catalog.json` (461/461 iso).
            -/

            import PNPLab.MembershipTransport

            namespace PNPLab.Resolution

            """
        )
    )


def _write_part_footer(
    f: TextIO, part_idx: int, names: list[str], start_idx: int, count: int
) -> None:
    flags = ", ".join(f"{p}TopologySetEq" for p in names)
    proofs = ", ".join(f"{p}TopologySetEq_true" for p in names)
    f.write(
        textwrap.dedent(
            f"""\
            def residualClosureTopologyFlagsPart{part_idx} : List Bool :=
              [{flags}]

            theorem all_residual_closure_topology_part{part_idx} :
                residualClosureTopologyFlagsPart{part_idx}.all (· = true) := by
              native_decide

            theorem residual_closure_part{part_idx}_count :
                residualClosureTopologyFlagsPart{part_idx}.length = {count} := by
              native_decide

            def residualClosurePart{part_idx}Doc : String :=
              "rc{start_idx}..rc{start_idx + count - 1}"

            end PNPLab.Resolution
            """
        )
    )


def _emit_part(
    part_idx: int,
    chunk: list[dict],
    global_start: int,
    target: frozenset[tuple[int, ...]],
) -> list[str]:
    count = len(chunk)
    start_idx = global_start
    out = LEAN_DIR / f"ResidualClosurePart{part_idx}.lean"
    names: list[str] = []

    with out.open("w", encoding="utf-8", newline="\n") as f:
        _write_part_header(f, part_idx, count, start_idx)
        for local_i, inst in enumerate(chunk):
            global_idx = global_start + local_i
            pre = f"rc{global_idx}"
            n = inst["n"]
            c1, c2 = inst["chords"]
            c1t, c2t = tuple(c1), tuple(c2)

            res = residual_of(n, c1t, c2t)
            assert res["shape_ok"], (global_idx, n, c1, c2)
            assert res["tips"] == inst["tips"], (global_idx, res["tips"], inst["tips"])
            assert res["Vres"] == inst["Vres"], (global_idx, res["Vres"], inst["Vres"])

            wit = inst.get("witness")
            assert wit is not None and inst["iso_found"]
            assert not wit.get("needs_flips", False), (global_idx, n, c1, c2)
            perm = list(wit["permutation"])

            check = _find_signed_iso(res["RAxioms"], res["Vres"], target)
            assert check is not None and not check["needs_flips"], (
                global_idx,
                n,
                c1,
                c2,
            )

            names.append(pre)
            f.write(_emit_instance_block(global_idx, inst, res, perm))

        _write_part_footer(f, part_idx, names, start_idx, count)

    print(f"wrote {out} entries={count} bytes={out.stat().st_size}")
    return names


def _emit_all(total: int, part_sizes: list[int]) -> None:
    out = LEAN_DIR / "ResidualClosureAll.lean"
    n_parts = len(part_sizes)
    imports = "\n".join(
        f"import PNPLab.ResidualClosurePart{i}" for i in range(1, n_parts + 1)
    )
    parts_flags = " ++ ".join(
        f"residualClosureTopologyFlagsPart{i}" for i in range(1, n_parts + 1)
    )
    part_props = " ∧\n  ".join(
        f"residualClosureTopologyFlagsPart{i}.all (· = true)"
        for i in range(1, n_parts + 1)
    )
    body = f"""/-
  Aggregated full residual closure topology set-eq ({total}/{total} catalog).

  Generated by `{EMIT_SCRIPT}`.
-/

{imports}
import PNPLab.CrossingResidualCatalog

namespace PNPLab.Resolution

def allResidualClosureTopologyFlags : List Bool :=
  {parts_flags}

theorem all_residual_closures_topology_set_eq :
    allResidualClosureTopologyFlags.all (· = true) := by
  native_decide

theorem all_residual_closures_topology_set_eq_parts :
  {part_props} := by
  native_decide

theorem all_residual_closures_count :
    allResidualClosureTopologyFlags.length = {total} := by
  native_decide

theorem all_residual_closures_mass :
    allResidualClosureTopologyFlags.length = crossingResidualCatalogMass.isoOk ∧
      crossingResidualCatalogMass.isoOk = {total} := by
  native_decide

def residualClosureAllDoc : String :=
  "reports/discovery/crossing_residual_catalog.json"

end PNPLab.Resolution
"""
    out.write_text(body, encoding="utf-8")
    print(f"wrote {out} bytes={out.stat().st_size}")


def main() -> int:
    catalog = json.loads(CATALOG.read_text(encoding="utf-8"))
    instances = catalog["instances"]
    total = len(instances)
    assert total == catalog["iso_ok"] == 461, (total, catalog["iso_ok"])

    k4 = _extract_k4_axioms()
    target = _clause_set(k4)

    chunks: list[list[dict]] = []
    for i in range(0, total, CHUNK):
        chunks.append(instances[i : i + CHUNK])
    part_sizes = [len(c) for c in chunks[:3]]
    assert sum(part_sizes) == total, part_sizes

    global_start = 1
    all_names: list[str] = []
    LEAN_DIR.mkdir(parents=True, exist_ok=True)
    for part_idx, chunk in enumerate(chunks[:3], start=1):
        names = _emit_part(part_idx, chunk, global_start, target)
        all_names.extend(names)
        global_start += len(chunk)

    assert len(all_names) == total, len(all_names)
    _emit_all(total, part_sizes)
    print(f"total={total} parts={part_sizes}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
