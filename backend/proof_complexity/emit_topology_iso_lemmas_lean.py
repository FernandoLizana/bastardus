"""Emit Lean catalog iso witness tables (G5 residual→k4Closed transport).

Reads `crossing_residual_catalog.json` and writes three witness-only Lean parts
(~154 entries each): src, permutation, tips, n, chords — no full RAxioms.

Generic transport lemmas live in `CatalogIsoTransport.lean` (hand-maintained).
"""

from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
CATALOG = ROOT / "reports" / "discovery" / "crossing_residual_catalog.json"
LEAN_DIR = ROOT / "lean" / "PNPLab"
CHUNK = 154


def _nat_pair(p: list[int]) -> str:
    return f"({p[0]}, {p[1]})"


def _emit_entry(inst: dict) -> str:
    n = inst["n"]
    c1, c2 = inst["chords"]
    tips = inst["tips"]
    wit = inst["witness"]
    src = "[" + ", ".join(str(v) for v in wit["src"]) + "]"
    perm = "[" + ", ".join(str(v) for v in wit["permutation"]) + "]"
    return (
        f"  {{ n := {n}, tips := {tips}, "
        f"chord1 := {_nat_pair(c1)}, chord2 := {_nat_pair(c2)}, "
        f"src := {src}, permutation := {perm}, "
        f"src_len := by native_decide, perm_len := by native_decide }}"
    )


def _emit_part(part_idx: int, entries: list[dict]) -> str:
    name = f"catalogIsoWitnessesPart{part_idx}"
    lines = [
        f"/-",
        f"  E2 catalog iso witnesses part {part_idx} (Category C / G5).",
        f"  {len(entries)} instances — metadata only (no RAxioms).",
        f"  Generated by `emit_topology_iso_lemmas_lean.py`.",
        f"-/",
        f"",
        f"import PNPLab.CrossingResidualCatalog",
        f"",
        f"namespace PNPLab.Resolution",
        f"",
        f"def {name} : List CatalogIsoEntry :=",
        f"  [",
    ]
    for i, inst in enumerate(entries):
        suffix = "," if i + 1 < len(entries) else ""
        lines.append(_emit_entry(inst) + suffix)
    lines.extend(
        [
            f"  ]",
            f"",
            f"theorem {name}_length : {name}.length = {len(entries)} := by",
            f"  native_decide",
            f"",
            f"end PNPLab.Resolution",
            f"",
        ]
    )
    return "\n".join(lines)


def main() -> int:
    catalog = json.loads(CATALOG.read_text(encoding="utf-8"))
    instances = catalog["instances"]
    total = len(instances)
    assert total == catalog["iso_ok"] == 461, (total, catalog["iso_ok"])
    for inst in instances:
        assert inst["iso_found"] and inst["shape_ok"]
        wit = inst["witness"]
        assert not wit.get("needs_flips", False)

    chunks: list[list[dict]] = []
    for i in range(0, total, CHUNK):
        chunks.append(instances[i : i + CHUNK])
    while len(chunks) < 3:
        chunks.append([])

    part_sizes = [len(c) for c in chunks[:3]]
    assert sum(part_sizes) == total, part_sizes

    LEAN_DIR.mkdir(parents=True, exist_ok=True)
    for idx, chunk in enumerate(chunks[:3], start=1):
        out = LEAN_DIR / f"CatalogIsoPart{idx}.lean"
        out.write_text(_emit_part(idx, chunk), encoding="utf-8")
        print(f"wrote {out} entries={len(chunk)}")

    print(f"total={total} parts={part_sizes}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
